"""Opt-in, isolated tests of the built executable and its actual Python environment.

Set TOOLFRAME_TEST_EXECUTABLE and TOOLFRAME_TEST_POSTGRES_DSN. The PostgreSQL
fixture creates and drops its own database; application files live in tmp_path.
"""

import asyncio
import json
import os
import shutil
import socket
import subprocess
from pathlib import Path

import httpx
import pytest
from fastmcp import Client
from test_database_providers import provider as provider  # noqa: PLC0414


@pytest.mark.parametrize("provider", ["postgresql"], indirect=True)
def test_executable_target_switch_and_shared_entry_points(provider, tmp_path):
    binary = os.environ.get("TOOLFRAME_TEST_EXECUTABLE")
    if not binary:
        pytest.skip(
            "set TOOLFRAME_TEST_EXECUTABLE to an already-built Toolframe binary"
        )
    repository = Path(__file__).resolve().parents[2]
    shutil.copy2(binary, tmp_path / "toolframe")
    for directory in ("app", "domains"):
        shutil.copytree(
            repository / directory,
            tmp_path / directory,
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
        )
    (tmp_path / "workspace").mkdir()
    probe = tmp_path / "domains/probe"
    for directory in ("tools", "ui", "llms", "model", "migrations"):
        (probe / directory).mkdir(parents=True)
    (probe / "__init__.py").write_text("")
    for directory in ("tools", "model", "ui"):
        (probe / directory / "__init__.py").write_text("")
    (probe / "tools/probe_save.py").write_text('''# /// script
# requires-python = ">=3.14,<3.15"
# dependencies = []
# ///
from fastmcp.tools import tool
from toolframe_db import get_database

@tool
def probe_save(key: str, value: str) -> dict:
    """Store one test event and replay the result on retry."""
    result = get_database().run_once("probe.save", key, {"value": value}, lambda tx: {"id": tx.insert("probe_events", {"value": value}), "value": value})
    return {"data": result.value, "replayed": result.replayed}
''')
    for dialect, identity in (
        ("sqlite", "INTEGER PRIMARY KEY"),
        ("postgresql", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
    ):
        (probe / f"migrations/{dialect}.sql").write_text(
            f"CREATE TABLE probe_events (id {identity}, value TEXT NOT NULL UNIQUE);"
        )
    (probe / "migrations/schema.json").write_text(
        json.dumps(
            {
                "owner": "probe",
                "target": "1",
                "revisions": [
                    {
                        "revision": "1",
                        "sql": {"sqlite": "sqlite.sql", "postgresql": "postgresql.sql"},
                        "tables": ["probe_events"],
                    }
                ],
            }
        )
    )
    with socket.socket() as available:
        available.bind(("127.0.0.1", 0))
        port = available.getsockname()[1]
    runtime = Path(os.environ.get("TOOLFRAME_TEST_RUNTIME", tmp_path / ".toolframe"))
    common = [
        str(tmp_path / "toolframe"),
        "--runtime-dir",
        str(runtime),
        "--uv-path",
        shutil.which("uv"),
        "--host",
        "127.0.0.1",
        "--port",
        str(port),
        "--port-search-span",
        "1",
    ]
    inherited = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith("TOOLFRAME_") and key not in {"PYTHONPATH", "VIRTUAL_ENV"}
    }
    dsn = provider.settings.postgres_dsn.get_secret_value()

    def environment(dialect):
        return {
            **inherited,
            "TOOLFRAME_DB_PROVIDER": dialect,
            **({"TOOLFRAME_POSTGRES_DSN": dsn} if dialect == "postgresql" else {}),
        }

    def command(dialect, *args, overrides=None):
        result = subprocess.run(
            [*common, *args],
            cwd=tmp_path,
            env={**environment(dialect), **(overrides or {})},
            capture_output=True,
            timeout=240,
            check=False,
        )
        assert dsn.encode() not in result.stdout + result.stderr
        if result.returncode:
            # Logs are local fixture diagnostics. Never print raw connection input.
            (tmp_path / f"{dialect}-{args[0]}.log").write_bytes(
                result.stdout + result.stderr
            )
            pytest.fail(
                f"{dialect} {args[0]} exited {result.returncode}; inspect the fixture log"
            )
        return json.loads(result.stdout)

    async def exercise():
        for index, dialect in enumerate(("sqlite", "postgresql", "sqlite")):
            checked = command(dialect, "check", "--format", "json")
            assert checked["database"]["provider"] == dialect
            assert checked["databaseMutated"] is False
            assert checked["migrations"]["validationLevel"] == (
                "schema-trial" if dialect == "sqlite" else "history-and-plan"
            )
            if index == 0:
                assert not (tmp_path / "data").exists()
            payload = {"key": dialect, "value": dialect}
            first = command(
                dialect, "invoke", "probe_save", "--json", json.dumps(payload)
            )
            assert first["ok"]
            assert first["result"][1]["replayed"] is (index == 2)
            duplicate = command(
                dialect, "invoke", "probe_save", "--json", json.dumps(payload)
            )
            assert duplicate["result"][1]["replayed"] is True
            with (tmp_path / f"{dialect}-serve.log").open("ab") as log:
                child = await asyncio.create_subprocess_exec(
                    *common,
                    "serve",
                    cwd=tmp_path,
                    env=environment(dialect),
                    stdout=log,
                    stderr=log,
                )
                url = f"http://127.0.0.1:{port}"
                try:
                    async with httpx.AsyncClient() as client:
                        for _ in range(240):
                            assert child.returncode is None, (
                                "server stopped before readiness"
                            )
                            try:
                                response = await client.get(url + "/api/runtime")
                                if response.status_code == 200:
                                    break
                            except httpx.HTTPError:
                                pass
                            await asyncio.sleep(0.25)
                        else:
                            pytest.fail("server readiness timed out")
                        info = response.json()
                        assert info["database"]["provider"] == dialect
                        assert set(info["migrations"]["applied"]) == {
                            "legacy@0000",
                            "legacy@0001",
                            "probe@1",
                        }
                        assert any(
                            plugin["name"] == "toolframe.database." + dialect
                            and plugin["provides"] == "toolframe.database"
                            for plugin in info["plugins"]
                        )
                        assert dsn not in response.text
                        assert (await client.get(url + "/info")).status_code == 200
                        assert (await client.get(url + "/")).status_code == 200
                        preview = (await client.get(url + "/api/database")).json()
                        events = next(
                            table
                            for table in preview["tables"]
                            if table["name"] == "probe_events"
                        )
                        assert (
                            len(events["rows"]) == 1 and events["rows"][0][1] == dialect
                        )
                        async with Client(url + "/mcp") as mcp:
                            assert (await mcp.call_tool("probe_save", payload)).data[
                                "replayed"
                            ] is True
                            assert (
                                await mcp.call_tool(
                                    "entry_register_list_entries", {"limit": 50}
                                )
                            ).data["entries"] == []
                            assert (
                                await client.post(
                                    url + "/api/plugins/domain.probe/disable"
                                )
                            ).status_code == 200
                            denied = await mcp.call_tool(
                                "probe_save",
                                {"key": "disabled", "value": "disabled"},
                                raise_on_error=False,
                            )
                            assert denied.is_error
                            assert (
                                await client.post(
                                    url + "/api/plugins/domain.probe/enable"
                                )
                            ).status_code == 200
                            assert (await mcp.call_tool("probe_save", payload)).data[
                                "replayed"
                            ] is True
                finally:
                    child.terminate()
                    try:
                        await asyncio.wait_for(child.wait(), timeout=20)
                    except TimeoutError:
                        child.kill()
                        await child.wait()

    for filename, flags, overrides in (
        (
            "cli.db",
            ("--database", "cli.db"),
            {"TOOLFRAME_SQLITE_PATH": "preferred.db", "TOOLFRAME_DB": "legacy.db"},
        ),
        (
            "preferred.db",
            (),
            {"TOOLFRAME_SQLITE_PATH": "preferred.db", "TOOLFRAME_DB": "legacy.db"},
        ),
        ("legacy.db", (), {"TOOLFRAME_DB": "legacy.db"}),
    ):
        checked = command(
            "sqlite", "check", "--format", "json", *flags, overrides=overrides
        )
        assert checked["database"]["target"] == str((tmp_path / filename).resolve())
        assert not (tmp_path / filename).exists()
    asyncio.run(exercise())
    original = (probe / "migrations/sqlite.sql").read_bytes()
    draft = command("sqlite", "scaffold", "migration", "probe", "add_note")
    assert draft["revision"] == "probe@0001_add_note" and draft["draft"] is True
    assert (probe / "migrations/sqlite.sql").read_bytes() == original
    assert all(Path(path).is_file() for path in draft["sources"])
