def test_postgres_literals_and_secret_safe_failures(tmp_path, caplog):
    from toolframe_database_postgresql import PostgreSQLProvider, _bind

    sql, values = _bind(
        "SELECT $$:ignore 100%$$, $tag$:ignore$tag$, 1::int, :x", {"x": 7}
    )
    assert sql == "SELECT $$:ignore 100%%$$, $tag$:ignore$tag$, 1::int, %(x)s"
    assert values == {"x": 7}
    settings = DatabaseSettings(
        provider="postgresql",
        sqlite_path=tmp_path / "unused.db",
        postgres_dsn="postgresql://nobody:NEVER-LOG-THIS@127.0.0.1:1/nonexistent",
        timeout_seconds=1,
    )
    db = PostgreSQLProvider(settings)
    try:
        with (
            caplog.at_level(logging.ERROR),
            pytest.raises(DashboardDatabaseError) as raised,
        ):
            db.query("SELECT 1")
        assert "NEVER-LOG-THIS" not in str(raised.value)
        assert "NEVER-LOG-THIS" not in caplog.text
        assert raised.value.__suppress_context__
    finally:
        db.close()


def test_lock_timeout_is_retryable_and_connections_recover(provider):
    provider.insert("contract_entries", {"value": "locked"})
    impatient = create_provider(
        provider.settings.model_copy(
            update={
                "timeout_seconds": 0.05,
                "pool_timeout_seconds": 0.05,
                "pool_size": 1,
            }
        )
    )
    try:
        with provider.connection() as holder:
            holder.execute("BEGIN").close()
            holder.execute("UPDATE contract_entries SET amount=1").close()
            with pytest.raises(DashboardDatabaseError) as raised:
                impatient.execute("UPDATE contract_entries SET amount=2")
            assert raised.value.code == "database_busy" and raised.value.retryable
            holder.rollback()
        assert (
            impatient.execute("UPDATE contract_entries SET amount=3").affected_rows == 1
        )
        if provider.dialect == "postgresql":
            with impatient.connection(), pytest.raises(DashboardDatabaseError) as pool:
                impatient.query("SELECT 1")
            assert pool.value.code == "database_busy"
            assert impatient.query("SELECT 1").iloc[0, 0] == 1
    finally:
        impatient.close()


def test_statement_timeout_applies_to_expensive_queries(provider):
    impatient = create_provider(
        provider.settings.model_copy(update={"timeout_seconds": 0.03})
    )
    try:
        # This ordinary recursive query is portable and would take much longer
        # than the configured budget without the provider's statement timeout.
        with pytest.raises(DashboardDatabaseError) as raised:
            impatient.query(
                "WITH RECURSIVE n(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM n WHERE x<100000000) SELECT SUM(x) FROM n"
            )
        assert raised.value.code == "database_busy"
        assert impatient.query("SELECT 1").iloc[0, 0] == 1
    finally:
        impatient.close()


def test_receipt_corruption_and_oversized_result_fail_without_business_commit(provider):
    provider.run_once("contract.receipt", "corrupt", {}, lambda tx: {"ok": True})
    with provider.connection() as connection:
        connection.execute(
            "UPDATE _toolframe_idempotency SET result_json=:bad", {"bad": b"bad"}
        ).close()
        connection.commit()
    with pytest.raises(IdempotencyError) as raised:
        provider.run_once(
            "contract.receipt", "corrupt", {}, lambda tx: pytest.fail("must not rerun")
        )
    assert raised.value.code == "idempotency_record_corrupt"

    def oversized(tx):
        tx.insert("contract_entries", {"value": "rollback"})
        return {"large": "x" * 1048576}

    with pytest.raises(IdempotencyError) as raised:
        provider.run_once("contract.receipt", "large", {}, oversized)
    assert raised.value.code == "idempotency_result_too_large"
    assert provider.query("SELECT * FROM contract_entries").empty


def test_unchanged_entry_domain_uses_either_provider(provider):
    path = (
        Path(__file__).resolve().parents[2] / "domains/entry_register/model/entries.py"
    )
    spec = importlib.util.spec_from_file_location("portable_entry_model", path)
    model = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(model)
    identity = (
        "INTEGER PRIMARY KEY"
        if provider.dialect == "sqlite"
        else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    with provider.connection() as connection:
        connection.execute(
            f"CREATE TABLE entry_register_entries (id {identity}, label TEXT NOT NULL, value DOUBLE PRECISION NOT NULL, version INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)"
        ).close()
        connection.commit()
    identifier = model.add_entry(provider, label="  portable  ", value=3)
    assert model.list_entries(provider).iloc[0]["label"] == "portable"
    model.update_entry(
        provider, entry_id=identifier, expected_version=1, label="changed", value=4
    )
    row = model.list_entries(provider).iloc[0]
    assert row["label"] == "changed" and row["version"] == 2
    assert row["updated_at"].endswith("Z")
    with pytest.raises(model.EntryConflictError):
        model.update_entry(
            provider, entry_id=identifier, expected_version=1, label="stale", value=5
        )


def test_idempotent_reference_tool_uses_current_domain_and_portable_id(
    provider, monkeypatch
):
    import runpy

    from toolframe_domain_imports import prepare_domains
    from toolframe_idempotency import _configure
    from toolframe_migrations import MigrationCoordinator, discover_domains

    repository = Path(__file__).resolve().parents[2]
    monkeypatch.syspath_prepend(str(repository))
    # Other host tests prepare different apps in this same Python process.
    prepare_domains(repository / "domains", reset=True)
    schemas, legacy = discover_domains(repository / "domains")
    MigrationCoordinator(provider, schemas, legacy=legacy).apply()
    _configure(provider=provider)
    example = runpy.run_path(str(repository / "examples/idempotent_create_entry.py"))
    create = example["idempotent_create_entry"]
    first = create("example-key", "Example", 4.5)
    duplicate = create("example-key", "Example", 4.5)
    assert first["entry"] == duplicate["entry"]
    assert isinstance(first["entry"]["id"], int)
    assert first["replayed"] is False and duplicate["replayed"] is True
    assert provider.query("SELECT label FROM entry_register_entries")[
        "label"
    ].tolist() == ["Example"]
