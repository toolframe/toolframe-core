@pytest.fixture(params=["sqlite", "postgresql"])
def provider(request, tmp_path):
    dialect = request.param
    admin = None
    database_name = None
    options = {"sqlite_path": tmp_path / "contract.db", "provider": dialect}
    if dialect == "postgresql":
        dsn = os.environ.get("TOOLFRAME_TEST_POSTGRES_DSN")
        if not dsn:
            pytest.skip(
                "set TOOLFRAME_TEST_POSTGRES_DSN to a disposable PostgreSQL server"
            )
        import psycopg
        from psycopg import sql
        from sqlalchemy.engine import make_url

        admin = psycopg.connect(dsn, autocommit=True)
        database_name = "toolframe_test_" + uuid.uuid4().hex
        admin.execute(
            sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name))
        )
        options["postgres_dsn"] = (
            make_url(dsn)
            .set(database=database_name)
            .render_as_string(hide_password=False)
        )
    result = create_provider(DatabaseSettings(**options))
    try:
        with result.connection() as connection:
            identity = (
                "INTEGER PRIMARY KEY"
                if dialect == "sqlite"
                else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            )
            connection.execute(
                f"CREATE TABLE contract_entries (id {identity}, value TEXT NOT NULL UNIQUE, amount INTEGER NOT NULL DEFAULT 0)"
            ).close()
            receipts = (
                _RECEIPT_SCHEMA
                if dialect == "sqlite"
                else """
                CREATE TABLE _toolframe_idempotency (
                    namespace TEXT NOT NULL, business_key TEXT NOT NULL,
                    input_sha256 TEXT NOT NULL CHECK(length(input_sha256)=64),
                    result_json BYTEA NOT NULL, result_sha256 TEXT NOT NULL CHECK(length(result_sha256)=64),
                    result_bytes INTEGER NOT NULL CHECK(result_bytes BETWEEN 1 AND 1048576),
                    original_operation_id TEXT NOT NULL,
                    completed_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    PRIMARY KEY(namespace, business_key)
                )
            """
            )
            connection.execute(receipts).close()
            connection.commit()
        yield result
    finally:
        result.close()
        if admin is not None:
            try:
                admin.execute(
                    sql.SQL("DROP DATABASE {} WITH (FORCE)").format(
                        sql.Identifier(database_name)
                    )
                )
            finally:
                admin.close()


def test_portable_crud_and_typed_service(provider):
    assert isinstance(provider, DatabaseProvider)
    assert DATABASE.validate(provider) is provider
    identifier = provider.insert("contract_entries", {"value": "hello", "amount": 3})
    assert isinstance(identifier, int) and identifier > 0
    row = provider.query(
        "SELECT id, value, amount FROM contract_entries WHERE id=:id",
        {"id": identifier},
    ).iloc[0]
    assert row["value"] == "hello" and row["amount"] == 3
    result = provider.execute(
        "UPDATE contract_entries SET amount=:amount WHERE id=:id",
        {"amount": 9, "id": identifier},
    )
    assert result.affected_rows == 1
    assert (
        provider.execute(
            "DELETE FROM contract_entries WHERE id=:id", {"id": identifier}
        ).affected_rows
        == 1
    )
    assert provider.query("SELECT * FROM contract_entries").empty


def test_transactions_rollback_and_poison_after_caught_failure(provider):
    with provider.transaction() as transaction:
        identifier = transaction.insert("contract_entries", {"value": "committed"})
        assert (
            transaction.query("SELECT id FROM contract_entries").iloc[0, 0]
            == identifier
        )
    with (
        pytest.raises(RuntimeError, match="cancel"),
        provider.transaction() as transaction,
    ):
        transaction.insert("contract_entries", {"value": "rolled-back"})
        raise RuntimeError("cancel")
    with (
        pytest.raises(DashboardDatabaseError) as raised,
        provider.transaction() as transaction,
    ):
        transaction.insert("contract_entries", {"value": "also-rolled-back"})
        with pytest.raises(DashboardDatabaseError) as duplicate:
            transaction.insert("contract_entries", {"value": "committed"})
        assert duplicate.value.code == "constraint_violation"
    assert raised.value.code == "transaction_aborted"
    assert provider.query("SELECT value FROM contract_entries")["value"].tolist() == [
        "committed"
    ]
    with pytest.raises(DashboardDatabaseError) as closed:
        transaction.query("SELECT 1")
    assert closed.value.code == "transaction_closed"


