SQL = "toolframe.sql"
PROVIDERS = {"alpha": "sql-sqlite", "beta": "sql-postgres"}


def portable_store(directory, name, *, revision=1):
    source = store_source(directory, name, revision=revision)
    module = source / "fixture/__init__.py"
    module.write_text(
        module.read_text()
        .replace(
            "sql='CREATE TABLE records(id INTEGER PRIMARY KEY, label TEXT NOT NULL);'",
            "sql='CREATE TABLE records(id INTEGER PRIMARY KEY, label TEXT NOT NULL);',"
            "dialects={'postgresql':'CREATE TABLE records(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label TEXT NOT NULL);'}",
        )
        .replace(
            'sql="ALTER TABLE records ADD COLUMN version INTEGER NOT NULL DEFAULT 1;"',
            'sql="ALTER TABLE records ADD COLUMN version INTEGER NOT NULL DEFAULT 1;",'
            'dialects={"postgresql":"ALTER TABLE records ADD COLUMN version INTEGER NOT NULL DEFAULT 1;"}',
        )
        .replace(
            "'write':MethodSpec(audience=\"internal\", )",
            "'standalone':MethodSpec(audience=\"internal\"),'write':MethodSpec(audience=\"internal\")",
        )
        .replace(
            "        async with storage.transaction",
            "        if method=='standalone':\n"
            "            return await storage.execute('INSERT INTO records(label) VALUES (?)',[params['label']])\n"
            "        async with storage.transaction",
        )
    )
    return source


@pytest.fixture
async def mixed(host, tmp_path, monkeypatch):
    admin = os.environ.get("TOOLFRAME_CORE_TEST_ADMIN_DSN")
    if not admin:
        pytest.skip("Set TOOLFRAME_CORE_TEST_ADMIN_DSN for mixed SQL worker tests")
    psycopg = pytest.importorskip("psycopg")
    pytest.importorskip("toolframe_sql_postgres")
    from psycopg import sql
    from toolframe_sql_postgres.config import names
    from toolframe_sql_postgres.provision import provision

    database = "tf_mixed_" + uuid.uuid4().hex
    application = host.composition.application.id
    owners = ("alpha", "beta", "gamma")
    environment = provision(admin, database, application, owners)
    for key, value in environment.items():
        monkeypatch.setenv(key, value)
    try:
        composition = host.composition.model_copy(deep=True)
        composition.bindings = {
            SQL: "sql-postgres",
            "alpha/sql": "sql-sqlite",
        }
        atomic_write(host.config.path, tomlkit.dumps(composition.model_dump()))
        workspace = Path(__file__).resolve().parents[2]
        for provider in ("sql-sqlite", "sql-postgres"):
            result = await operate(
                host,
                "add",
                source=str(workspace / f"toolframe-{provider}"),
                enable=True,
            )
            assert result["status"] == "succeeded", result
        for name in owners:
            source = portable_store(tmp_path, name)
            result = await operate(host, "add", source=str(source), enable=True)
            assert result["status"] == "succeeded", result
        yield host
    finally:
        await host.close()
        with psycopg.connect(admin, autocommit=True) as connection:
            connection.execute(
                sql.SQL("DROP DATABASE {} WITH (FORCE)").format(
                    sql.Identifier(database)
                )
            )
            for owner in owners:
                roles = names(application, owner, database=database)
                for key in ("controller", "runtime"):
                    connection.execute(
                        sql.SQL("DROP ROLE {}").format(sql.Identifier(roles[key]))
                    )
            connection.execute(
                sql.SQL("DROP ROLE {}").format(
                    sql.Identifier(names(application, database=database)["manager"])
                )
            )


async def read(host, owner):
    return await host.call_service(owner, f"{owner}.service", "read", {})


async def test_mixed_routing_isolation_drain_disable_and_retained_restart(
    mixed, tmp_path
):
    host = mixed
    for owner in PROVIDERS:
        await host.call_service(
            owner, f"{owner}.service", "standalone", {"label": owner}
        )
        assert await read(host, owner) == [{"id": 1, "label": owner}]
    assert await read(host, "gamma") == []
    assert host.graph.stores == {**PROVIDERS, "gamma": "sql-postgres"}
    assert (await host.status())["stores"]["beta"][
        "retained_provider"
    ] == "sql-postgres"
    for owner, provider in PROVIDERS.items():
        other = "beta" if owner == "alpha" else "alpha"
        old = {name: runtime.generation for name, runtime in host.runtimes.items()}
        call = asyncio.create_task(
            host.call_service(
                owner, f"{owner}.service", "write", {"label": "drained", "delay": 1}
            )
        )
        await until(
            lambda owner=owner: any(
                root.owner == owner and not root.read_only
                for root in host.roots.values()
            )
        )
        replacement = asyncio.create_task(operate(host, "reload", id=provider))
        expected = [{"id": 1, "label": other}]
        if owner == "beta":
            expected.append({"id": 2, "label": "drained"})
        assert await read(host, other) == expected
        assert await call == {"written": True}
        assert (await replacement)["status"] == "succeeded"
        assert host.runtimes[owner].generation != old[owner]
        assert host.runtimes[other].generation == old[other]
        assert host.runtimes[PROVIDERS[other]].generation == old[PROVIDERS[other]]
        assert (await operate(host, "disable", id=provider))["status"] == "succeeded"
        with pytest.raises(PluginError):
            await read(host, owner)
        assert await read(host, other)
        assert (await operate(host, "enable", id=provider))["status"] == "succeeded"
        assert [row["label"] for row in await read(host, owner)] == [owner, "drained"]
    assert (await operate(host, "remove", id="alpha"))["status"] == "succeeded"
    # Reinstall the retained source; removing a plugin must not forget its store.
    result = await operate(
        host, "add", id="alpha", source=str(tmp_path / "alpha"), enable=True
    )
    assert result["status"] == "succeeded", result
    home = host.home
    await host.close()
    restarted = await Host.create(home)
    try:
        await restarted.start()
        assert [row["label"] for row in await read(restarted, "alpha")] == [
            "alpha",
            "drained",
        ]
        assert [row["label"] for row in await read(restarted, "beta")] == [
            "beta",
            "drained",
        ]
        composition = restarted.composition.model_copy(deep=True)
        composition.bindings["alpha/sql"] = "sql-postgres"
        atomic_write(restarted.config.path, tomlkit.dumps(composition.model_dump()))
        failed = await operate(restarted, "apply")
        assert failed["error"]["code"] == "store_rebind_required", failed
        assert (await read(restarted, "alpha"))[0]["label"] == "alpha"
    finally:
        await restarted.close()
    # Editing the binding while stopped must not bypass retained ownership either.
    restarted = await Host.create(home)
    try:
        await restarted.start()
        assert not restarted.runtimes
        assert (await restarted.status())["stores"]["alpha"][
            "retained_provider"
        ] == "sql-sqlite"
        composition.bindings["alpha/sql"] = "sql-sqlite"
        atomic_write(restarted.config.path, tomlkit.dumps(composition.model_dump()))
        assert (await operate(restarted, "apply"))["status"] == "succeeded"
        assert (await read(restarted, "alpha"))[0]["label"] == "alpha"
    finally:
        await restarted.close()


@pytest.mark.parametrize("owner", ["alpha", "beta"])
async def test_mixed_migration_tokens_and_unknown_commit_recovery(
    mixed, tmp_path, monkeypatch, owner
):
    host = mixed
    provider = PROVIDERS[owner]
    other = "beta" if owner == "alpha" else "alpha"
    await host.call_service(owner, f"{owner}.service", "write", {"label": "retained"})
    portable_store(tmp_path, owner, revision=2)
    plan = await operate(host, "migrate-plan", id=owner)
    assert plan["status"] == "succeeded", plan
    assert plan["result"]["provider"] == provider
    assert (await operate(host, "reload", id=provider))["status"] == "succeeded"
    stale = await operate(
        host, "migrate-apply", id=owner, plan_id=plan["result"]["plan_id"]
    )
    assert stale["error"]["code"] == "stale_plan", stale
    plan = await operate(host, "migrate-plan", id=owner)
    real_admin = host.admin

    async def lost_ack(storage, method, params):
        result = await real_admin(storage, method, params)
        if storage.name == provider and method == "apply":
            raise PluginError("rpc_timeout", "Commit reply was lost")
        return result

    monkeypatch.setattr(host, "admin", lost_ack)
    failed = await operate(
        host, "migrate-apply", id=owner, plan_id=plan["result"]["plan_id"]
    )
    assert failed["error"]["code"] == "forward_repair_required", failed
    assert owner not in host.runtimes
    assert await read(host, other) == []
    repair = (await host.status())["forward_repair"]
    assert repair["schemas"][0]["provider"] == provider
    blocked = await operate(host, "reload", id=other)
    assert blocked["error"]["code"] == "forward_repair_required", blocked
    assert (await host.status())["forward_repair"] == repair
    monkeypatch.setattr(host, "admin", real_admin)
    if owner == "beta":
        await host.close()
        host = await Host.create(host.home)
    try:
        if host is not mixed:
            await host.start()
            assert not host.runtimes
            assert (await host.status())["forward_repair"] == repair
        assert (await operate(host, "reload", id=owner))["status"] == "succeeded"
        assert await read(host, owner) == [{"id": 1, "label": "retained", "version": 1}]
        assert (await host.status())["forward_repair"] is None
        assert await read(host, "gamma") == []
    finally:
        if host is not mixed:
            await host.close()
